#!/usr/bin/env python3
"""Plot measured encrypted spatial coverage, including input and client layer 1."""
import csv
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import PercentFormatter
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'benchmarks/resnet_client_first_slots8192_20261024'
OUT=SOURCE/'figures'
OUT.mkdir(exist_ok=True)
series={}; records=[]
for area in range(10,81,10):
    folder=SOURCE/f'area{area:02d}'
    with (folder/'layers.csv.client.csv').open() as f: client=next(csv.DictReader(f))
    rows=[dict(conv_layers=0,height=224,width=224,encrypted_h_start=client['original_h_start'],encrypted_h_end=client['original_h_end'],encrypted_w_start=client['original_w_start'],encrypted_w_end=client['original_w_end']),dict(client,conv_layers=1)]
    with (folder/'layers.csv').open() as f: rows.extend(csv.DictReader(f))
    assert [int(r['conv_layers']) for r in rows]==list(range(9))
    values=[]
    for r in rows:
        h=int(r['encrypted_h_end'])-int(r['encrypted_h_start'])+1
        w=int(r['encrypted_w_end'])-int(r['encrypted_w_start'])+1
        height,width=int(r['height']),int(r['width'])
        assert 0<h<=height and 0<w<=width
        ratio=h*w/(height*width)
        values.append(100*ratio)
        records.append(dict(initial_area=area,layer=int(r['conv_layers']),feature_height=height,feature_width=width,encrypted_height=h,encrypted_width=w,encrypted_percent=100*ratio))
    series[area]=values
with (OUT/'encrypted_region_ratio.csv').open('w',newline='') as f:
    writer=csv.writer(f);writer.writerow(['Layer']+[f'{a}x{a} (%)' for a in series])
    for layer in range(9):writer.writerow([layer]+[round(v[layer],6) for v in series.values()])
with (OUT/'encrypted_region_geometry.csv').open('w',newline='') as f:
    writer=csv.DictWriter(f,fieldnames=list(records[0]));writer.writeheader();writer.writerows(records)
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':11,'axes.edgecolor':'#dadce0','axes.labelcolor':'#5f6368','xtick.color':'#5f6368','ytick.color':'#5f6368','svg.fonttype':'none'})
colors=['#4285F4','#DB4437','#F4B400','#0F9D58','#AB47BC','#00ACC1','#FF7043','#5C6BC0']
fig,ax=plt.subplots(figsize=(12.8,7.2),facecolor='white')
fig.subplots_adjust(left=.09,right=.84,top=.80,bottom=.25)
ax.set_axisbelow(True);ax.grid(axis='y',color='#e8eaed',linewidth=.85)
for (area,values),color in zip(series.items(),colors):
    ax.plot(range(9),values,color=color,linewidth=2.3,marker='o',markersize=5,label=f'{area} × {area}')
ax.set_xlim(-.12,8.12);ax.set_ylim(0,100)
ax.set_xticks(range(9),['Input\n0','Client\n1','2','3','4','5','6','7','8'])
ax.set_yticks(range(0,101,10));ax.yaxis.set_major_formatter(PercentFormatter(100,decimals=0))
ax.set_xlabel('Original convolution layer',labelpad=13);ax.set_ylabel('Encrypted spatial coverage',labelpad=12)
ax.spines[['top','right']].set_visible(False);ax.tick_params(axis='both',length=0,pad=9)
legend=ax.legend(title='Initial center region',loc='center left',bbox_to_anchor=(1.025,.5),frameon=False,labelspacing=1.05,handlelength=2.1)
plt.setp(legend.get_title(),color='#5f6368',fontsize=10)
fig.text(.09,.925,'How encrypted coverage grows across layers',fontsize=21,color='#202124',weight='medium')
fig.text(.09,.872,'Center regions 10 × 10 to 80 × 80  •  Client computes layer 1; server computes layers 2–8',fontsize=11.5,color='#5f6368')
fig.text(.09,.045,'Coverage = (encrypted rectangle height × width) / (feature-map height × width).\nAll channels share the spatial mask; values come from recorded layouts, not ciphertext slot utilization.',fontsize=9.5,color='#5f6368',linespacing=1.7)
for ext in ('png','svg','pdf'):fig.savefig(OUT/f'encrypted_region_ratio.{ext}',dpi=220,facecolor='white')
plt.close(fig)
(OUT/'README.md').write_text('''# Encrypted spatial coverage by layer

Generated by `scripts/plot_encrypted_region_ratio.py` from each area's `layers.csv.client.csv` (input and layer 1) and `layers.csv` (layers 2–8).

Coverage is the inclusive encrypted rectangle area divided by the output feature-map spatial area. Channel count cancels because the same rectangle applies to all channels. It is not the fraction of nonzero slots or ciphertext storage. Input is 224×224; layer 1 is 112×112; layers 2–6 are 56×56; layers 7–8 are 28×28. Layer 1 runs on the client. The original sensitive center is expanded conservatively by receptive-field overlap.

- `encrypted_region_ratio.png`: preview / slides.
- `encrypted_region_ratio.svg` and `.pdf`: vector export.
- `encrypted_region_ratio.csv`: wide percentage table for Google Sheets; select the table and insert a line chart.
- `encrypted_region_geometry.csv`: dimensions and percentages for auditing.
''')
print(OUT)
print('Layer 8 percentages:', {a:round(v[8],3) for a,v in series.items()})
